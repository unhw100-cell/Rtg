object StringsProvider {
  val ru: AppStrings by lazy { RustBridge.getLocalizedStrings("ru") }
  val en: AppStrings by lazy { RustBridge.getLocalizedStrings("en") }

  fun forLang(lang: String): AppStrings =
    if (lang.trim().equals("en", ignoreCase = true)) en else ru
}
